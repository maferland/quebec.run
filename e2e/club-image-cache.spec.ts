import 'dotenv/config'
import { test, expect } from '@playwright/test'
import { encode } from 'next-auth/jwt'
import { Pool } from 'pg'

test('club images retain their pixels, refresh on rename, and disappear on deletion', async ({
  request,
  baseURL,
}) => {
  test.skip(!process.env.CI, 'Requires a production build')
  expect(new URL(baseURL!).hostname).toBe('localhost')
  const databaseUrl = new URL(process.env.DATABASE_URL!)
  expect(['localhost', '127.0.0.1']).toContain(databaseUrl.hostname)
  expect(databaseUrl.pathname).toMatch(/test|club_og_cache/)
  const pool = new Pool({ connectionString: databaseUrl.toString() })
  let club: { id: string; slug: string } | undefined
  let deleted = false
  let headers: Record<string, string> = {}
  try {
    // Reuse a user generated by the local seed; all fixture mutations go
    // through the authenticated APIs so their invalidation runs for real.
    const { rows } = await pool.query<{ id: string }>(
      'SELECT id FROM users LIMIT 1'
    )
    expect(rows[0]?.id).toBeTruthy()
    const token = await encode({
      secret: 'playwright-local-fixture-secret-at-least-32-characters',
      token: { sub: rows[0].id },
    })
    headers = { cookie: `next-auth.session-token=${token}` }
    await request.get('/api/explore/clubs')
    const created = await request.post('/api/clubs', {
      headers,
      data: { name: `Image fixture ${Date.now()}` },
    })
    expect(created.status()).toBe(201)
    club = await created.json()
    await expect(async () => {
      const list = await (await request.get('/api/explore/clubs')).json()
      expect(list.some((entry: { id: string }) => entry.id === club!.id)).toBe(
        true
      )
    }).toPass({ timeout: 15000 })
    const images = new Map<string, Buffer>()
    for (const locale of ['en', 'fr']) {
      const path = `/${locale}/clubs/${club!.slug}/opengraph-image`
      const first = await request.get(path)
      expect(first.status()).toBe(200)
      expect(first.headers()['x-nextjs-cache']).toBe('MISS')
      expect(first.headers()['content-type']).toContain('image/png')
      images.set(locale, await first.body())
      await expect(async () => {
        const cached = await request.get(path)
        expect(cached.headers()['x-nextjs-cache']).toBe('HIT')
        expect(await cached.body()).toEqual(images.get(locale))
      }).toPass({ timeout: 15000 })
    }

    const renamed = await request.put(`/api/clubs/${club!.slug}`, {
      headers,
      data: { id: club!.id, name: 'Renamed image fixture' },
    })
    expect(renamed.ok()).toBe(true)
    await expect(async () => {
      const list = await (await request.get('/api/explore/clubs')).json()
      expect(
        list.find((entry: { id: string }) => entry.id === club!.id)?.name
      ).toBe('Renamed image fixture')
    }).toPass({ timeout: 15000 })
    for (const locale of ['en', 'fr']) {
      await expect(async () => {
        const image = await request.get(
          `/${locale}/clubs/${club!.slug}/opengraph-image`
        )
        expect(image.status()).toBe(200)
        expect(await image.body()).not.toEqual(images.get(locale))
      }).toPass({ timeout: 15000 })
    }

    const response = await request.delete(
      `/api/clubs/${club!.slug}?id=${club!.id}`,
      { headers }
    )
    expect(response.ok()).toBe(true)
    deleted = true
    await expect(async () => {
      const list = await (await request.get('/api/explore/clubs')).json()
      expect(list.some((entry: { id: string }) => entry.id === club!.id)).toBe(
        false
      )
    }).toPass({ timeout: 15000 })
    for (const locale of ['en', 'fr']) {
      await expect(async () => {
        expect(
          (
            await request.get(`/${locale}/clubs/${club!.slug}/opengraph-image`)
          ).status()
        ).toBe(404)
      }).toPass({ timeout: 15000 })
    }
  } finally {
    // A failed assertion must not leave local fixtures behind.
    if (club && !deleted) {
      const response = await request.delete(
        `/api/clubs/${club.slug}?id=${club.id}`,
        { headers }
      )
      expect(response.ok()).toBe(true)
    }
    await pool.end()
  }
})
